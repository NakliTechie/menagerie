#!/usr/bin/env node
// Generates ./acp-types.ts from the pinned ACP v1 JSON Schema in ./vendor/.
//
//   node generate-acp-types.mjs
//
// The output is a build artifact: DO NOT hand-edit acp-types.ts — change this
// generator or the vendored schema instead. Regeneration must produce no diff
// (v1.1 handoff, checkpoint C0).
//
// Pin recorded in ./acp-pin.md. Zero dependencies; Node >= 18.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = join(here, "vendor", "acp-schema-v1.json");
const outPath = join(here, "acp-types.ts");

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));

// Pin identity — must match protocol/acp-pin.md.
const PIN_COMMIT = "b7f0005493b98de32fabee3e9540e2b64da68535";
const PIN_PATH = "schema/v1/schema.json";

// ---- helpers ----------------------------------------------------------

const refName = (ref) => {
  const m = /^#\/\$defs\/(.+)$/.exec(ref);
  if (!m) throw new Error(`unsupported $ref: ${ref}`);
  return m[1];
};

/** Render a schema's description as a JSDoc block ("" when absent). */
function jsdoc(s, indent = "") {
  const d = s?.description;
  if (!d) return "";
  const body = d
    .split("\n")
    .map((l) => l.trimEnd())
    .join("\n")
    .replace(/\*\//g, "*\\/");
  const lines = body.split("\n").map((l) => `${indent} *${l ? " " + l : ""}`);
  return `${indent}/**\n${lines.join("\n")}\n${indent} */\n`;
}

const keyOk = (k) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k);

/** Single JSON-Schema `type` value -> TS type expression. */
function scalar(t, s) {
  switch (t) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return s.items !== undefined ? `${ts(s.items)}[]` : "unknown[]";
    case "object":
      return objectType(s);
    default:
      return "unknown";
  }
}

/** Object schema -> inline TS object type literal. */
function objectType(s) {
  const lines = [];
  for (const [k, v] of Object.entries(s.properties ?? {})) {
    const opt = (s.required ?? []).includes(k) ? "" : "?";
    lines.push(`${jsdoc(v, "  ")}  ${keyOk(k) ? k : JSON.stringify(k)}${opt}: ${ts(v)};`);
  }
  if (s.additionalProperties === true) lines.push("  [k: string]: unknown;");
  else if (s.additionalProperties && typeof s.additionalProperties === "object") {
    // Only emit an index signature when there are no declared properties to conflict with.
    if (!Object.keys(s.properties ?? {}).length) {
      lines.push(`  [k: string]: ${ts(s.additionalProperties)};`);
    }
  }
  return lines.length ? `{\n${lines.join("\n")}\n}` : "{ [k: string]: unknown }";
}

/** Any schema -> TS type expression. Pure function of the input JSON. */
function ts(s) {
  if (s === true) return "unknown";
  if (s === false || s == null || typeof s !== "object") return "never";
  if (s.$ref) return refName(s.$ref);
  if (s.allOf) {
    const base = s.allOf.map(ts).map(wrapUnion).join(" & ");
    // A tagged-union variant carries its own discriminator properties alongside
    // an allOf base (e.g. SessionUpdate's `sessionUpdate` const + $ref body).
    // Intersect them or the union loses its discriminators.
    if (Object.keys(s.properties ?? {}).length) return `${objectType(s)} & ${base}`;
    return base;
  }
  if (s.anyOf || s.oneOf) {
    const variants = (s.anyOf ?? s.oneOf).map((v) => {
      let t = ts(v);
      // Drop a variant's own doc from the expression; docs are attached at the def level.
      return t;
    });
    return dedupe(variants).join(" | ");
  }
  if ("const" in s) return JSON.stringify(s.const);
  if (s.enum) return dedupe(s.enum.map((e) => JSON.stringify(e))).join(" | ");
  if (Array.isArray(s.type)) return dedupe(s.type.map((t) => scalar(t, s))).join(" | ");
  if (typeof s.type === "string") return scalar(s.type, s);
  return "unknown";
}

const wrapUnion = (t) => (t.includes("|") ? `(${t})` : t);
function dedupe(arr) {
  return [...new Set(arr)];
}

// ---- defs -------------------------------------------------------------

const defs = schema.$defs ?? {};
const defNames = Object.keys(defs).sort((a, b) => a.localeCompare(b));

let out = "";
out += `/**\n * ACP (Agent Client Protocol) message types — GENERATED FILE.\n *\n`;
out += ` * Source: agentclientprotocol/agent-client-protocol @ ${PIN_COMMIT}\n`;
out += ` *         ${PIN_PATH}\n`;
out += ` * Generated by: protocol/generate-acp-types.mjs (regen must produce no diff).\n`;
out += ` * Do not edit by hand; do not import Menagerie types into this file —\n`;
out += ` * the ACP pin stays swappable without a protocol major (handoff §C1).\n`;
out += ` */\n\n`;

for (const name of defNames) {
  const def = defs[name];
  out += jsdoc(def);
  out += `export type ${name} = ${ts(def)};\n\n`;
}

// ---- envelope aliases from the root anyOf ------------------------------

for (const entry of schema.anyOf ?? []) {
  let variants;
  if (entry.anyOf) {
    variants = dedupe(
      entry.anyOf.map((v) =>
        v.allOf && v.allOf.length === 1 && v.allOf[0].$ref ? refName(v.allOf[0].$ref) : ts(v),
      ),
    );
  } else {
    // Plain object envelope (e.g. protocol-level `$/…` notifications).
    variants = [ts(entry)];
  }
  out += `${jsdoc(entry)}export type ${entry.title}Message = ${variants.join(" | ")};\n\n`;
}

writeFileSync(outPath, out);
console.log(`wrote ${outPath} (${defNames.length} defs)`);
